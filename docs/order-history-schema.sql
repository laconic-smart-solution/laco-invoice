-- Order History / Audit Trail schema (Oracle)
-- Project uses Hibernate ddl-auto=update; this script documents the intended schema
-- for DBA review / environments where DDL auto is disabled.
-- Index/constraint names are kept ≤30 characters for Oracle compatibility.

-- order_history
CREATE TABLE order_history (
    id                    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              NUMBER(19) NOT NULL,
    action                VARCHAR2(20) NOT NULL,
    source                VARCHAR2(20) NOT NULL,
    performed_by_user_id  NUMBER(19),
    performed_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    import_file_id        NUMBER(19),
    note                  VARCHAR2(500),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_oh_source CHECK (source IN ('MANUAL', 'IMPORT_EXCEL')),
    CONSTRAINT ck_oh_action CHECK (action IN ('CREATE', 'UPDATE', 'DELETE')),
    CONSTRAINT ck_oh_import_file CHECK (
        (source = 'IMPORT_EXCEL' AND import_file_id IS NOT NULL)
        OR (source = 'MANUAL' AND import_file_id IS NULL)
    )
);

CREATE INDEX ix_oh_order_perf ON order_history (order_id, performed_at, id);
CREATE INDEX ix_order_history_import_file ON order_history (import_file_id);
CREATE INDEX ix_order_history_user ON order_history (performed_by_user_id);
CREATE INDEX ix_oh_source_perf ON order_history (source, performed_at);
CREATE INDEX ix_oh_action_perf ON order_history (action, performed_at);

-- order_history_changes
CREATE TABLE order_history_changes (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    history_id       NUMBER(19) NOT NULL,
    field_name       VARCHAR2(100) NOT NULL,
    field_label_key  VARCHAR2(150),
    old_value        VARCHAR2(2000),
    new_value        VARCHAR2(2000),
    value_type       VARCHAR2(20) NOT NULL,
    CONSTRAINT ux_ohc_hist_field UNIQUE (history_id, field_name),
    CONSTRAINT ck_ohc_value_type CHECK (
        value_type IN ('STRING','INTEGER','DECIMAL','BOOLEAN','DATE','DATETIME','ENUM','JSON','TEXT')
    )
);

CREATE INDEX ix_ohc_history ON order_history_changes (history_id);
